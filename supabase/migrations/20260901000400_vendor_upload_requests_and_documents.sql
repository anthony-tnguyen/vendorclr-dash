create table public.vendor_documents (
  id                 uuid primary key default gen_random_uuid(),
  company_id         uuid not null references public.companies (id) on delete cascade,
  vendor_id          uuid not null references public.vendors (id) on delete cascade,
  upload_request_id  uuid references public.vendor_upload_requests (id) on delete set null,
  -- Server-generated by buildStoragePath(); never derived from a client-supplied
  -- name. See src/workflows/uploadTokens.ts.
  storage_path       text not null unique,
  file_name          text not null,
  mime_type          text not null,
  file_size          bigint not null check (file_size > 0 and file_size <= 26214400),
  sha256             text not null,
  source             text not null default 'vendor_portal'
                       check (source in ('vendor_portal', 'client_upload', 'admin', 'email')),
  -- Phase 2 (OCR/extraction) will drive this past 'uploaded'. Uploading a file
  -- never implies compliance - see vendor_compliance_items, which this table
  -- does not touch.
  processing_status  text not null default 'uploaded'
                       check (processing_status in ('uploaded', 'processing', 'processed', 'needs_review', 'failed')),
  processing_error   text,
  uploaded_at        timestamptz not null default now(),
  processed_at       timestamptz,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);

