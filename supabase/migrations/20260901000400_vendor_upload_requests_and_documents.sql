-- Phase 1 / migration 4 - the outbound vendor request system, document storage,
-- and the closing half of the loop: vendor -> email -> magic link -> upload.
--
-- Security model for this migration specifically:
--
--   vendor_upload_requests has NO anon or public read/write policy, on purpose.
--   The vendor opening a magic link has no Supabase session - there is no
--   auth.uid() to write a policy against. Resolving a token instead goes through
--   the resolveUploadToken() / uploadDocumentForToken() server functions
--   (src/workflows/vendorUploadRequests.ts), which use the service-role key
--   to bypass RLS *after* independently verifying the hashed token, its expiry,
--   and its status. RLS on this table protects the request metadata from other
--   *tenants*; it deliberately does not gate the anonymous portal, because it
--   cannot - that job belongs to the token check.
--
--   token_hash stores SHA-256 of the token, never the token itself. A dump of
--   this table does not hand out working upload links.

create table public.vendor_upload_requests (
  id             uuid primary key default gen_random_uuid(),
  company_id     uuid not null references public.companies (id) on delete cascade,
  vendor_id      uuid not null references public.vendors (id) on delete cascade,
  token_hash     text not null unique,
  purpose        text not null default 'renewal' check (purpose in ('renewal', 'initial', 'correction')),
  status         text not null default 'pending' check (status in (
                   'pending', 'email_sent', 'opened', 'uploaded', 'processing',
                   'completed', 'needs_review', 'expired', 'cancelled'
                 )),
  expires_at     timestamptz not null,
  opened_at      timestamptz,
  uploaded_at    timestamptz,
  completed_at   timestamptz,
  created_by     uuid references auth.users (id) on delete set null,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create index vendor_upload_requests_vendor_idx on public.vendor_upload_requests (vendor_id);
create index vendor_upload_requests_company_idx on public.vendor_upload_requests (company_id);
-- Powers the "which requests still need a nudge" queries Phase 3 reminders will run.
create index vendor_upload_requests_open_idx on public.vendor_upload_requests (expires_at)
  where status not in ('completed', 'expired', 'cancelled');

create trigger vendor_upload_requests_touch_updated_at
  before update on public.vendor_upload_requests
  for each row execute function public.touch_updated_at();

-- vendor_id is not null here, so the existing generic trigger applies unchanged.
create trigger vendor_upload_requests_company_matches_vendor
  before insert or update on public.vendor_upload_requests
  for each row execute function public.assert_company_matches_vendor();

alter table public.vendor_upload_requests enable row level security;

-- Company members can see and create requests for their own vendors, same as
-- every other company-scoped table. There is intentionally no anon policy.
create policy vendor_upload_requests_select on public.vendor_upload_requests
  for select to authenticated
  using (company_id in (select public.current_company_ids()) or public.is_platform_admin());

create policy vendor_upload_requests_insert on public.vendor_upload_requests
  for insert to authenticated
  with check (public.can_write_company(company_id));

create policy vendor_upload_requests_update on public.vendor_upload_requests
  for update to authenticated
  using (public.can_write_company(company_id))
  with check (public.can_write_company(company_id));

-- No delete policy: a request is evidence of what was asked and when: it should
-- expire or be cancelled, not disappear from the audit trail.

