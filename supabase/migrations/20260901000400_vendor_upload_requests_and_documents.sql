insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'vendor-documents',
  'vendor-documents',
  false,
  26214400, -- 25 MB, matches vendor_documents.file_size and MAX_UPLOAD_BYTES in src/workflows/uploadTokens.ts
  array['application/pdf', 'image/jpeg', 'image/png']
)
on conflict (id) do nothing;

-- Objects are written exclusively through uploadDocumentForToken() using the
-- service-role key (which bypasses storage RLS same as table RLS), because the
-- uploader is an anonymous vendor with no session. This policy therefore only
-- ever needs to grant *read* access, to authenticated company members viewing
-- their own vendor's documents - there is no authenticated write path to allow.
--
-- storage.foldername() splits the object path on '/' and drops the file name,
-- so for "company/<companyId>/vendor/<vendorId>/documents/<id>.pdf" segment
-- [2] is the companyId.
-- The uuid cast on the folder segment is guarded by a regex match first: AND is
-- not guaranteed left-to-right by the planner, so without the guard a future
-- bucket whose paths don't start with a uuid segment could make this policy
-- throw (not just return false) when both policies are evaluated in the same
-- scan of storage.objects.
create policy vendor_documents_bucket_read on storage.objects
  for select to authenticated
  using (
    bucket_id = 'vendor-documents'
    and (storage.foldername(name))[1] = 'company'
    and (storage.foldername(name))[2] ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
    and ((storage.foldername(name))[2])::uuid in (select public.current_company_ids())
  );
